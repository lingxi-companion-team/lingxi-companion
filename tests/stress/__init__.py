"""压测与模糊标定套件（C 主责）。

⚠️ 本包**必须单独运行，且不要带覆盖率插桩**
==========================================

.. code-block:: console

    python -m pytest tests/stress -q            # 正确
    python -m pytest tests/stress -q --cov      # 会随机变红

为什么（2026-10-02 实测，同一台机器、同一条测试，唯一变量是 ``--cov``）：

===============  =======================  =================
运行方式          串行链路单帧中位耗时       预算 20 ms
===============  =======================  =================
不带 ``--cov``    2.02 ms                  通过（10 倍余量）
带 ``--cov``      **22.05 ms**             **超预算 10%**
===============  =======================  =================

``coverage`` 的逐行追踪让纯 Python 执行慢约**一个数量级**。而本包里有一条预算
**是从产品指标推出来的**：端到端单帧必须快于采集间隔 ``1000 / pipeline.target_fps``
（默认 66.7 ms），否则处理追不上采集、队列必然积压。**在插桩下量它，
等于用一把被拉长的尺子量产品指标** —— 要么随机变红，要么为了让它变绿而把
产品指标改松。两种结果都不能接受。

所以 CI（``.github/workflows/tests.yml``）把它拆成两步：主步骤带 ``--cov``
但 ``--ignore=tests/stress``；紧接着一步**不带插桩**专跑本包。
两步在**同一个 job** 里，所以压测失败照样会让 ``pytest (3.x)`` 这个
required check 变红 —— 分开只是换了尺子，不是放行。

本地跑全套门禁时同理：

.. code-block:: console

    python -m pytest -q --cov --cov-fail-under=80 --ignore=tests/stress
    python -m pytest tests/stress -q

⚠️ 另外注意：本包的预算刻意取得**很松**（见各文件里常量的取值理由）。
它针对的不是性能认证，而是**数量级退化** —— 例如有人把环境智能体从
「固定 32×32 采样点」改成「遍历全帧像素」（480p 是 30 万次），耗时跳 2~3 个
数量级，预算照样拦得住。把预算压到接近实测值只会让 CI 在繁忙时随机变红，
而**随机变红的压测等于没有压测**（大家会习惯性重跑）。
"""
