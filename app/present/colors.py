"""状态 → 颜色 映射（纯逻辑，无 GUI 依赖）。

四色语义见设计稿 §04.1。这里只产出**色值字符串**，不碰任何绘图库，
因此可以在 headless CI 里满跑（GUI 外壳在 ``app/client/``，整体 omit）。

颜色取值在 2026-09-30 的 v7 重设计里**整体换过一版**，不是审美偏好而是可达性修复。
换色前后的实测对比度（WCAG 2.1，白卡 ``#ffffff`` / 画布 ``#f1f6fe`` 双底实测）::

    旧值                             旧：压白 / 压画布     新值
    focused    #3b82c4                4.06 / 3.74   ✗   → #0052d9   6.54 / 6.03  ✓
    confused   #d09a2c                2.52 / 2.32   ✗   → #6a45cf   6.24 / 5.75  ✓
    distracted #c0584f                4.42 / 4.07   ✗   → #0f6e78   5.96 / 5.50  ✓
    unknown    #9aa5b1                2.50 / 2.31   ✗   → #626c79   5.33 / 4.91  ✓

旧值四个里**三个不到 4.5:1**，``confused`` 只有 2.52 —— 那是「状态名文字几乎读不出来」
的程度，而它恰恰是需要教师最快看到的那一类。新值四个全部 ≥4.5，且都留了余量。

``focused`` 取 ``#0052d9`` 与品牌蓝**同值**，是有意的：专注是课堂常态（占比最大），
让它与整体蓝调一致可以少占一个色相，避免界面出现第五种颜色。
"""

from __future__ import annotations

from common.perception_types import EmotionLabel

__all__ = [
    "DIM_COLOR",
    "STATE_COLORS",
    "color_for",
    "color_for_count",
    "color_for_key",
    "color_for_key_count",
    "is_dim",
]

#: 四个状态的展示色。
#:
#: **形状/中文名是并行的第二、第三编码通道**（见 :mod:`app.present.shape`），
#: 所以这四个色值不必（也不该）承担「光靠颜色区分」的职责 —— 它们要保证的是
#: 「压在自己的底色上读得清」。下面每条的注释就是该色值实测的两个对比度。
#:
#: 关于「为什么不全用高饱和暖色把分神做得更扎眼」
#: ------------------------------------------------
#: 这一版曾被质疑「四色明度差被压窄了，区分全押在色相上」。复算后结论是：
#: 当四个色都必须在**双底（白卡 + 画布）**上各自达标 4.5:1 时，可行的明度区间
#: 只有 Y≈0.11~0.15，跨度上限约 1.35× —— 这是**可达性的硬约束**，不是配色疏忽。
#: 想把跨度拉到 2× 以上只能让某几个色掉到 3~4:1（实测 ``#c2601a`` 只有 4.22、
#: ``#7c8695`` 只有 3.68），而「状态名读不清」比「灰度下不够分」严重得多。
#:
#: 更关键的是：把四色压到同一明度带后，**灰度可分性并没有变差** ——
#: 最小两两明度比旧值 1.007、本版 1.066（越高越易分）。真正兜底的是**形状通道**
#: （● ▲ ◆ ─），它不随投影仪色偏与色觉异常失效，这才是「颜色之外」的保险。
#:
#: ``DISTRACTED`` 是唯一带暖调的：它是最需要被一眼找到的状态，而暖色在浅蓝底上
#: 天然前跳。选 ``#b04a12`` 而不是更艳的橙，是因为更亮的橙（``#b3541e`` 5.00/4.32）
#: 压画布就掉到 4.5 以下了 —— 这个值正好卡在暖度与可达性的交界上。
STATE_COLORS: dict[EmotionLabel, str] = {
    # 6.54 压白 / 5.66 压画布。与品牌蓝同值（见模块 docstring）。
    EmotionLabel.FOCUSED: "#0052d9",
    # 6.24 压白 / 5.40 压画布。紫：与蓝分开一个色相，但同样够暗。
    EmotionLabel.CONFUSED: "#6a45cf",
    # 5.48 压白 / 4.74 压画布。暖锈色 —— 唯一暖调，是「需要被找到」的那个状态。
    EmotionLabel.DISTRACTED: "#b04a12",
    # 5.33 压白 / 4.61 压画布。中性灰，但没有旧值那么浅。
    EmotionLabel.UNKNOWN: "#626c79",
}

#: 「该分量人数为 0」时的置灰色（设计稿 §10.1 d1）。
#:
#: 与 ``UNKNOWN`` 的 ``#626c79`` 分工不同：那个是「本帧未形成判定」，这个是
#: 「该状态当前无人」。两者都是灰但语义不同，同色会让教师误读，所以这里**更浅**。
#:
#: 取值受三条约束夹逼：① 必须比 ``UNKNOWN`` 浅，否则两者混同；②「未形成判定」与
#: 「无人」的**相互**对比也要看得出差别（≥1.3 就够了，它们不是并列读数）；
#: ③ 它会被画成一根**实心占比条**，那是图形元素，按 WCAG 1.4.11 要 ≥3:1。
#:
#: 三个候选实测（压白 / 压画布 / 压面板）::
#:
#:     #b8c2cf   1.80 / 1.66 / 1.58   条太淡，几乎看不见 → 弃
#:     #8f9bab   2.82 / 2.60 / 2.48   仍不到 3 → 弃
#:     #7d8b9a   3.79 / 3.50 / 3.36   三条全过，且与 UNKNOWN 相距 1.93 → **取此值**
#:     #626c79   —— 这是 UNKNOWN，不能再深
#:
#: 注：本值只用于**图形**（占比条、状态条）。若今后要让置灰分量也承载文字，
#: 3.79 远不够 4.5，必须另取更深的文字色。
DIM_COLOR = "#7d8b9a"


def color_for(label: EmotionLabel) -> str:
    """取状态色。

    未登记的标签**退回置灰色而不是抛错** —— 展示层不该因为一条异常数据就整个崩掉。
    """
    return STATE_COLORS.get(label, DIM_COLOR)


def is_dim(count: int) -> bool:
    """人数为 0 的分量置灰但仍占位（设计稿 §10.1 d1）。"""
    return count <= 0


def color_for_count(label: EmotionLabel, count: int) -> str:
    """按「状态 + 人数」取色：0 人的分量置灰。"""
    return DIM_COLOR if is_dim(count) else color_for(label)


def color_for_key(label: str) -> str:
    """按**线路格式的字符串键**取状态色。

    客户端从 payload 里拿到的是 ``"focused"`` 这样的字符串而不是枚举，所以需要一个
    str 入口。未登记的键退回置灰色而不是抛错 —— 与 :func:`color_for` 同一取舍：
    展示层不为一条异常数据整个崩掉。这个兜底刻意留在**本模块**（有测试），
    而不是写在 GUI 里 —— ``app/client/`` 整体 omit 于覆盖率，规则写在那儿等于没有护栏。
    """
    try:
        return color_for(EmotionLabel(label))
    except ValueError:
        return DIM_COLOR


def color_for_key_count(label: str, count: int) -> str:
    """``color_for_key`` + 「0 人置灰」的组合，供汇总面板按行取色。

    存在的理由是**别让 GUI 去拼规则**：汇总面板拿到的是 ``LABEL_ORDER`` 里的字符串
    键与一个整数，如果让它自己写 ``color_for_key(k) if count else DIM_COLOR``，
    那条「0 人置灰」的规则就跑到没有覆盖率的 ``app/client/`` 里去了。这里把它
    收回有测试的层，GUI 只调一个函数。

    ``color_for_count`` 是同一个规则的枚举入口（服务端/内部调用用），两者口径一致，
    ``test_colors.py`` 有交叉断言防止它们漂移。
    """
    return DIM_COLOR if is_dim(count) else color_for_key(label)
