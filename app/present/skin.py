#: **只画线**，不承载信息。曾用来写「无结果」文字（2.6:1 读不出来），已降级。
INK_3 = "#8a9bb2"
#: 图例、脚注这类最小号说明文字。比 ``INK_2`` 再淡但仍过 4.5（5.22 压白）。
