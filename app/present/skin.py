#: 禁用：浅蓝底**不能**配白字（1.83:1），只能配深色文字。
BRAND_DISABLED = "#d4e0f4"

# ── 「已隐藏」格 ────────────────────────────────────────────────────────
#: 刻意不用红/警示色 —— 需求文档 §模块二.2 的公开开关是**权利**不是过失，
