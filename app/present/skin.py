# ── 表面 ────────────────────────────────────────────────────────────────
#: 画布底色。刻意**不用纯白** —— 一屏白卡压在纯白上会糊成一张电子表格。
#: 压白卡 1.156（15.6% 亮度差），是「卡片立得起来」的那条线。
BG = "#e8effb"
#: 卡片底色。白只留给卡片。
CARD_BG = "#ffffff"
#: 顶栏 / 侧栏（框架面）底色。比画布**浅**一档 —— 面板里要写状态名与百分比，
#: 底色一旦压深，那些文字就会掉到 4.5 以下（``#dfe9f9`` 会让 distracted 掉到 4.48）。
PANEL_BG = "#f0f6ff"
#: 顶栏与面板同值，让「顶栏 + 侧栏」读起来是一个连续的框架面。
HEADER_BG = PANEL_BG
#: 悬停 / 选中态底色。亮色主题下强调要变**深**，所以它比画布深。
BRAND_SUBTLE = "#d3e2fa"
#: 卡片阴影。取「画布压深一档」的浅蓝灰，压画布 1.154 —— 与「白卡 vs 画布」
#: 同一量级，读起来是卡片下缘的一点厚度，而不是一块糊上去的灰。
SHADOW = "#d5e0f0"

# ── 发丝线（带蓝不带灰）────────────────────────────────────────────────
