"""v8 统一页的**界面皮肤**令牌（纯数据，无 GUI、无第三方依赖）。

与 :mod:`app.present.colors` 的分工
------------------------------------
- ``colors.py`` 管**状态色**（绿/黄/红/灰），它有业务语义、有 ``EmotionLabel`` 键、
  有双令牌模型 —— 那是**规则**；
- 本模块管**表面、文字、发丝线、标签底、间距、圆角** —— 那是**皮肤**。
  它与业务无关：不知道什么是「专注」，也不认识任何枚举。

两者共同构成一套完整色板，但**权威定义各自独立**，谁也不重复定义对方的值。
``app/client/theme.py``（Tk 旧界面）里有它自己的一份 v7 皮肤 —— 那是**另一套设计**，
不是同一件事的两份拷贝，所以刻意不合并：v7 是蓝白两带 + 品牌蓝承载「专注」，
v8 按需求文档把状态交给绿黄红灰，表面留蓝白做「框架」。硬把两者合并，
只会得到一堆两套设计都不满意的折中值。

为什么放在 ``app/present/`` 而不是 ``app/web/``
------------------------------------------------
``app/web/*`` 整体 omit 于覆盖率（它 import flet，而 CI 不装 flet），
而本模块是**纯数据**：CI 里 import 得到，也就**测得动**。
``tests/app/present/test_skin.py`` 复算每一条色值的对比度 —— 与状态色同一套门槛。
放在 ``app/web/`` 里的话，这些 hex 就永远没有护栏了。

门槛（与 ``tests/app/client/test_contrast.py`` 同源）
-----------------------------------------------------
- **文字**（承载信息）：≥ 4.5:1（WCAG 1.4.3 AA）
- **图形元素**（描边、色条、占比条）：≥ 3:1（WCAG 1.4.11）
- **纯装饰**（虚线边框、分隔线）：不按 3:1 验，但仍断言「别浅到看不见」（≥1.8）——
  否则等于没画，而「没画」与「画了看不见」在视觉上是同一件事。

表面三档为什么是这三个值
------------------------
::

    白卡 / 画布   1.156      ← 28 张卡要靠这条差「一块块」立起来
    白卡 / 面板   1.086      ← 面板是框架面，比画布浅，但必须与白卡分得开
    画布 / 面板   1.064

投影仪把 8% 的亮度差压成 0 是常事，所以画布不能只比白卡浅一点点。
``#e8effb`` 这条差是 15.6%，同时四个状态 ink **仍然全部达标**（最低 4.76 压画布）。
"""

